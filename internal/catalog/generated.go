package catalog

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"slices"
	"strings"

	"go.yaml.in/yaml/v3"
)

// Annotations of generated objects and patches (design 5.4, 5.5).
const (
	AnnotationGeneratedBy    = "gaia/generated-by"    // Kind/name of the Source
	AnnotationSourceRevision = "gaia/source-revision" // what the Source read
	AnnotationContentHash    = "gaia/content-hash"    // sha256 of kind, name, labels and spec
	AnnotationMode           = "gaia/mode"            // patch
)

// Patchable are the spec fields a patch may set on a generated object of
// each kind; the rest belong to the object's source.
var Patchable = map[string][]string{
	KindTeam:    {"displayName", "secrets", "notifications"},
	KindNetwork: {"allowedEnvironments", "description"},
}

// PatchableLabels are the kinds whose generated objects may get labels
// from a patch (metadata.labels, merged).
var PatchableLabels = map[string]bool{KindNetwork: true}

// Generated reports whether the object was written by a Source.
func (o *Object) Generated() bool { return o.Metadata.Annotations[AnnotationGeneratedBy] != "" }

// ContentHash is the hash a generated object carries: of its kind, name,
// labels and spec, so that an edit by hand shows.
func ContentHash(kind, name string, labels map[string]string, spec *yaml.Node) (string, error) {
	var v any
	if spec != nil {
		if err := spec.Decode(&v); err != nil {
			return "", err
		}
	}
	if labels == nil {
		labels = map[string]string{}
	}
	b, err := json.Marshal(map[string]any{"kind": kind, "name": name, "labels": labels, "spec": v})
	if err != nil {
		return "", err
	}
	sum := sha256.Sum256(b)
	return "sha256:" + hex.EncodeToString(sum[:]), nil
}

// Render writes a generated object as YAML, with its annotations and
// content hash.
func Render(kind, name string, labels map[string]string, spec any, by, revision string) ([]byte, error) {
	var node yaml.Node
	if err := node.Encode(spec); err != nil {
		return nil, err
	}
	hash, err := ContentHash(kind, name, labels, &node)
	if err != nil {
		return nil, err
	}
	doc := struct {
		APIVersion string `yaml:"apiVersion"`
		Kind       string `yaml:"kind"`
		Metadata   struct {
			Name        string            `yaml:"name"`
			Labels      map[string]string `yaml:"labels,omitempty"`
			Annotations map[string]string `yaml:"annotations"`
		} `yaml:"metadata"`
		Spec *yaml.Node `yaml:"spec"`
	}{APIVersion: APIVersion, Kind: kind, Spec: &node}
	doc.Metadata.Name, doc.Metadata.Labels = name, labels
	doc.Metadata.Annotations = map[string]string{AnnotationGeneratedBy: by, AnnotationSourceRevision: revision, AnnotationContentHash: hash}
	var buf bytes.Buffer
	buf.WriteString("# Generated by " + by + "; do not edit. Patch it instead (design 5.5).\n")
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(doc); err != nil {
		return nil, err
	}
	return buf.Bytes(), enc.Close()
}

// specNode returns an object document's spec.
func specNode(root *yaml.Node) *yaml.Node {
	if root == nil || root.Kind != yaml.MappingNode {
		return nil
	}
	for i := 0; i+1 < len(root.Content); i += 2 {
		if root.Content[i].Value == "spec" {
			return root.Content[i+1]
		}
	}
	return nil
}

// checkGenerated verifies a generated object's content hash.
func checkGenerated(o *Object) string {
	want := o.Metadata.Annotations[AnnotationContentHash]
	got, err := ContentHash(o.Kind, o.Metadata.Name, o.Metadata.Labels, specNode(o.node))
	switch {
	case err != nil:
		return err.Error()
	case want == "":
		return "a generated object without " + AnnotationContentHash
	case want != got:
		return fmt.Sprintf("edited by hand: generated objects change only through %s; write a patch for what may be added (design 5.5)", o.Metadata.Annotations[AnnotationGeneratedBy])
	}
	return ""
}

// applyPatches merges patch objects into the generated objects they name.
func applyPatches(objects map[Key]*Object, patches []*Object) Errors {
	var errs Errors
	seen := map[Key]*Object{}
	for _, p := range patches {
		at := func(format string, a ...any) {
			errs = append(errs, Error{File: p.Source.File, Line: p.Source.Line, Object: p.Key().String() + " (patch)", Msg: fmt.Sprintf(format, a...)})
		}
		if prev, dup := seen[p.Key()]; dup {
			at("patched more than once (also at %s)", prev.Source)
			continue
		}
		seen[p.Key()] = p
		allowed, ok := Patchable[p.Kind]
		if !ok {
			at("%s objects cannot be patched", p.Kind)
			continue
		}
		target, ok := objects[p.Key()]
		switch {
		case !ok:
			at("no generated %s to patch", p.Key())
			continue
		case !target.Generated():
			at("%s is written by hand (%s); change it there", p.Key(), target.Source)
			continue
		}
		if len(p.Metadata.Labels) > 0 {
			if !PatchableLabels[p.Kind] {
				at("metadata.labels: %s objects get no labels from a patch", p.Kind)
				continue
			}
			if target.Metadata.Labels == nil {
				target.Metadata.Labels = map[string]string{}
			}
			for k, v := range p.Metadata.Labels {
				target.Metadata.Labels[k] = v
			}
		}
		pn, tn := specNode(p.node), specNode(target.node)
		if pn == nil && len(p.Metadata.Labels) > 0 {
			target.Patches = append(target.Patches, p.Source)
			continue
		}
		if pn == nil || pn.Kind != yaml.MappingNode || tn == nil || tn.Kind != yaml.MappingNode {
			at("spec: want a mapping")
			continue
		}
		merged := &yaml.Node{Kind: yaml.MappingNode, Tag: "!!map"}
		set := map[string]*yaml.Node{}
		var order []string
		for i := 0; i+1 < len(tn.Content); i += 2 {
			k := tn.Content[i].Value
			set[k], order = tn.Content[i+1], append(order, k)
		}
		bad := false
		for i := 0; i+1 < len(pn.Content); i += 2 {
			k := pn.Content[i].Value
			if !slices.Contains(allowed, k) {
				at("spec.%s belongs to %s; a patch may set %s", k, target.Metadata.Annotations[AnnotationGeneratedBy], strings.Join(allowed, ", "))
				bad = true
				continue
			}
			if _, ok := set[k]; !ok {
				order = append(order, k)
			}
			set[k] = pn.Content[i+1]
		}
		if bad {
			continue
		}
		for _, k := range order {
			merged.Content = append(merged.Content, &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: k}, set[k])
		}
		spec := newSpec[target.Kind]()
		if err := decodeStrictAt(merged, spec, "spec"); err != nil {
			at("%v", err)
			continue
		}
		if v, ok := spec.(validator); ok {
			if msgs := v.validate(); len(msgs) > 0 {
				at("spec.%s", strings.Join(msgs, "; spec."))
				continue
			}
		}
		target.Spec = spec
		target.Patches = append(target.Patches, p.Source)
	}
	return errs
}

// Validate runs a spec's own checks, for those who build specs.
func Validate(spec any) []string {
	if v, ok := spec.(validator); ok {
		return v.validate()
	}
	return nil
}
