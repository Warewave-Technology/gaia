const plural = (x: number, one: string, many: string) => `${n(x)} ${x === 1 ? one : many}`

/** ADR-007 C12: how much of the day a VM on a policy can be OK at best, from the server's max_ok_fraction (0..1). */
export function okShare(f: number): string {
  if (f >= 1) return 'all day'
  if (f <= 0) return 'never'
  if (f < 0.01) return 'less than 1 % of the day'
  return `at most ${Math.floor(f * 100)} % of the day` // floored: never more than the server said
}

