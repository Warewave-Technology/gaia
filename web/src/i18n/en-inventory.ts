function methodName(m: string) {
  return ({ webauthn: 'security key', totp: 'authenticator app', recovery_code: 'recovery code' } as Record<string, string>)[m] ?? m
}

function ordinal(x: number) {
  const s = x % 100 >= 11 && x % 100 <= 13 ? 'th' : ({ 1: 'st', 2: 'nd', 3: 'rd' } as Record<number, string>)[x % 10] ?? 'th'
  return `${x}${s}`
}
